const usedSlugs = new Set();

export const projectCount = projects.length;

export const normalizedProjects = projects.map((project, index) => {
  const projectNumber = String(index + 1).padStart(2, "0");
  const baseSlug = project.slug || `project-${projectNumber}`;
  let slug = baseSlug;

  if (usedSlugs.has(slug)) {
    slug = `${baseSlug}-${projectNumber}`;
  }

  usedSlugs.add(slug);

  return {
    ...project,
    id: projectNumber,
    slug,
    images: [...new Set(project.images || [project.image])],
  };
});

export { normalizedProjects as projects };



























